export const LoadOption =(conference,association,church)=>{
    const conferenceEl = document.getElementById(conference)
    const associationEl = document.getElementById(association)
    const churchEl = document.getElementById(church)
    

    // Set Conference, SetAssociation , SetChurch   functions called from OptionSet.jsx
    //Set Conference maps out only the conference
    if (conferenceEl) {
        SetConference(OptionData(), conferenceEl)

        //SetAssociation
        //Association setup maps the current selection from conference to the association options
        conferenceEl.onchange = (e) => {
            e.preventDefault();
            SetAssociation(OptionData(), associationEl, churchEl, conferenceEl)
        }

        //SetChurch
        //Church Setups maps the current selection from Association to the church options
        associationEl.onchange = (e) => {
            e.preventDefault();
            SetChurch(OptionData(), associationEl, conferenceEl, churchEl)
        }
    }
}
  

